// Checks the docs against the vendored Agentware compatibility data
// (scripts/data/agentware-compat.json, refreshed by scripts/sync-compat.mjs).
// Runs offline. Fails when:
// - overview.md does not carry the generated compat block for the vendored data, or
// - a page states an Agentware version other than the current VERSION without
//   writing it as a floor ("from X", "X or later"), or keeps its own
//   "Compatible versions:" line instead of linking to the shared block.
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const COMPAT_BEGIN = '<!-- compat:begin -->';
export const COMPAT_END = '<!-- compat:end -->';

const root = new URL('../', import.meta.url);
export const DATA_FILE = fileURLToPath(new URL('scripts/data/agentware-compat.json', root));
export const OVERVIEW_FILE = fileURLToPath(new URL('content/agentware/build/overview.md', root));
const CONTENT_DIR = fileURLToPath(new URL('content/', root));

// agentware 0.11.0, Agentware SDK 0.15.0, agentware/go v0.11.0, @haikeilabs/agentware@0.11.0, haikeilabs-agentware==0.11.0
const VERSION_MENTION = /\bagentware(?:\/(?:go|python|typescript)|\s+sdk)?(?:\s+|@|==)v?(\d+\.\d+\.\d+)\b/gi;
const FLOOR_WORDING = /\bfrom\b|\bor later\b|\band later\b|\bor newer\b|>=/i;
const OWN_COMPAT_LINE = /^\s*compatible versions:/i;

export async function readCompatData(file = DATA_FILE) {
  return JSON.parse(await readFile(file, 'utf8'));
}

export function renderCompatBlock(data) {
  const current = data.rows.find((row) => row.sdk === data.version);
  if (!current) throw new Error(`agentware VERSION ${data.version} has no row in the compatibility table`);
  return [
    COMPAT_BEGIN,
    '<!-- Generated by scripts/sync-compat.mjs from the agentware VERSION file and README compatibility table. Do not edit by hand; run npm run sync:compat. -->',
    '',
    `The current Agentware release is ${data.version}. It needs kei-proxy ${current.keiProxy} or later and kei-cli ${current.keiCli} or later. An older SDK version needs at least the runtime versions in its row:`,
    '',
    '| agentware SDK | kei-proxy (minimum) | kei-cli (minimum) |',
    '|---|---|---|',
    ...data.rows.map((row) => `| ${row.sdk} | ${row.keiProxy} | ${row.keiCli} |`),
    '',
    COMPAT_END,
  ].join('\n');
}

export function replaceCompatBlock(text, block) {
  const start = text.indexOf(COMPAT_BEGIN);
  const end = text.indexOf(COMPAT_END);
  if (start < 0 || end < start) throw new Error(`missing ${COMPAT_BEGIN} … ${COMPAT_END} markers`);
  return text.slice(0, start) + block + text.slice(end + COMPAT_END.length);
}

function withoutFrontMatterAndBlock(text) {
  // Blank out rather than remove, so reported line numbers stay right.
  const blank = (match) => match.replace(/[^\n]/g, '');
  let body = text.replace(/^---\n[\s\S]*?\n---\n/, blank);
  const start = body.indexOf(COMPAT_BEGIN);
  const end = body.indexOf(COMPAT_END);
  if (start >= 0 && end > start) body = body.slice(0, start) + blank(body.slice(start, end)) + body.slice(end);
  return body;
}

export function findVersionDrift(text, version) {
  const drift = [];
  withoutFrontMatterAndBlock(text).split('\n').forEach((line, index) => {
    if (OWN_COMPAT_LINE.test(line)) {
      drift.push({ line: index + 1, text: line.trim(), reason: 'own "Compatible versions" line; link to the shared block' });
      return;
    }
    for (const sentence of line.split(/(?<=[.!?])\s+/)) {
      const stale = [...sentence.matchAll(VERSION_MENTION)].filter((match) => match[1] !== version);
      if (stale.length && !FLOOR_WORDING.test(sentence)) {
        drift.push({ line: index + 1, text: line.trim(), reason: `Agentware ${stale[0][1]} is not the current ${version}; write "from ${stale[0][1]}" or "${stale[0][1]} or later"` });
        return;
      }
    }
  });
  return drift;
}

async function markdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await markdownFiles(absolute));
    else if (entry.isFile() && entry.name.endsWith('.md')) files.push(absolute);
  }
  return files.sort();
}

export async function checkCompat({ contentDir = CONTENT_DIR, dataFile = DATA_FILE, overviewFile = OVERVIEW_FILE } = {}) {
  const data = await readCompatData(dataFile);
  const problems = [];
  const overview = await readFile(overviewFile, 'utf8');
  if (!overview.includes(renderCompatBlock(data))) {
    problems.push(`${path.relative(contentDir, overviewFile)}: compat block is missing or stale; run npm run sync:compat`);
  }
  for (const file of await markdownFiles(contentDir)) {
    for (const item of findVersionDrift(await readFile(file, 'utf8'), data.version)) {
      problems.push(`${path.relative(contentDir, file)}:${item.line}: ${item.reason}\n    ${item.text}`);
    }
  }
  return { version: data.version, problems };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { version, problems } = await checkCompat();
  if (problems.length) {
    console.error(`Compatibility drift against agentware ${version}:\n${problems.join('\n')}`);
    process.exit(1);
  }
  console.log(`Compatibility check passed: docs match agentware ${version}.`);
}
